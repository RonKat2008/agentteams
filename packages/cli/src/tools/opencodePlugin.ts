import { isCommonStopLoop, readStringCwd } from './dialects.js';
import type { HookDialect } from './types.js';

export const OPENCODE_PLUGIN_MARKER = '// agentteams:managed - generated by "agentteams install"; edits are overwritten';

/**
 * OpenCode dialect (we own both sides): the hook prints `{"context": text}` or `{"block": text}`;
 * the generated plugin parses it. Nothing for `none`.
 */
export const opencodeDialect: HookDialect = {
  render(outcome) {
    if (outcome.type === 'context') return { stdout: JSON.stringify({ context: outcome.text }), exitCode: 0 };
    if (outcome.type === 'block') return { stdout: JSON.stringify({ block: outcome.text }), exitCode: 0 };
    return { stdout: '', exitCode: 0 };
  },
  readCwd: readStringCwd,
  isStopLoop: isCommonStopLoop,
};

/** Dependency-free ESM plugin (node built-ins only). Only `AgentTeams` is exported: OpenCode treats every export as a plugin. */
export function renderOpencodePlugin(node: string, cliBin: string): string {
  return `${OPENCODE_PLUGIN_MARKER}
import { spawn } from 'node:child_process';

const NODE = ${JSON.stringify(node)};
const CLI = ${JSON.stringify(cliBin)};
const HOOK_TIMEOUT_MS = 8000;

/** Runs \`agentteams hook <event> --tool opencode\`; resolves to { context?, block? } or null (never rejects). */
function runHook(event, input) {
  return new Promise((resolve) => {
    let out = '';
    let done = false;
    const finish = (v) => { if (!done) { done = true; clearTimeout(timer); resolve(v); } };
    let child;
    try {
      child = spawn(NODE, [CLI, 'hook', event, '--tool', 'opencode', '--agentteams-managed'], { stdio: ['pipe', 'pipe', 'ignore'] });
    } catch { resolve(null); return; }
    const timer = setTimeout(() => { try { child.kill(); } catch {} finish(null); }, HOOK_TIMEOUT_MS);
    child.on('error', () => finish(null));
    child.stdout.on('data', (d) => { out += d; });
    child.on('close', () => {
      try {
        const v = JSON.parse(out);
        finish(v && typeof v === 'object' ? v : null);
      } catch { finish(null); }
    });
    child.stdin.on('error', () => {});
    child.stdin.end(JSON.stringify(input));
  });
}

export const AgentTeams = async ({ client, directory }) => {
  const cwd = directory;
  // Sessions we just re-prompted: their next idle is sent as stop_hook_active, so the hub never blocks (or consumes)
  // twice in a row. No text-based dedupe: by the time we see a block the hub has already consumed those messages.
  const reprompted = new Set();

  const inject = (sessionID, text) =>
    client.session.prompt({ path: { id: sessionID }, body: { noReply: true, parts: [{ type: 'text', text }] } }).catch(() => {});

  return {
    event: async ({ event }) => {
      const props = (event && event.properties) || {};
      if (event.type === 'session.created') {
        const info = props.info || {};
        if (info.parentID || !info.id) return;
        const r = await runHook('session-start', { cwd });
        if (r && typeof r.context === 'string' && r.context !== '') await inject(info.id, r.context);
        return;
      }
      if (event.type === 'session.idle') {
        const id = props.sessionID;
        if (!id) return;
        const loop = reprompted.delete(id);
        const r = await runHook('stop', { cwd, stop_hook_active: loop });
        if (!r || typeof r.block !== 'string' || r.block === '') return;
        reprompted.add(id);
        // A real prompt (starts a turn). Not awaited: it resolves when the whole turn ends.
        client.session.prompt({ path: { id }, body: { parts: [{ type: 'text', text: r.block }] } }).catch(() => reprompted.delete(id));
      }
    },
    'tool.execute.after': async (input) => {
      const id = input && input.sessionID;
      if (!id) return;
      const r = await runHook('post-tool-use', { cwd });
      if (r && typeof r.context === 'string' && r.context !== '') await inject(id, r.context);
    },
  };
};
`;
}
